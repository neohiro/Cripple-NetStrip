"""Generate one page per subdomain from _data/hosts.yml.

THE RULE THIS SCRIPT ENFORCES
    _data/hosts.yml is the single source of truth. Every page under /hosts/,
    /artists/ and the per-subdomain directories is produced from it. Nothing
    about a host is written by hand anywhere, so the directory, the status
    report and the individual pages cannot drift apart.

WHAT IT WRITES
    artists/index.html            the artist category index
    artists/<slug>/index.html     one page per artist-category host
    <slug>/index.html             one page per every other host
    <slug>/index.html             for artists too, as a canonical pointer to
                                  /artists/<slug>/ so that EVERY host in the
                                  zone answers at /<slug>/, which is the
                                  address people actually type

IT IS IDEMPOTENT. Running it twice produces the same bytes. It will not clobber
a file it did not write: every generated file opens with the generator's
signature, and a file lacking that signature but present on disk is a hand-
edited page, which is reported and skipped rather than overwritten.

USAGE
    python scripts/build_host_pages.py            # write what changed
    python scripts/build_host_pages.py --check    # fail if anything is stale
    python scripts/build_host_pages.py --clean    # remove generated pages that
                                                  # no longer have a record
"""

