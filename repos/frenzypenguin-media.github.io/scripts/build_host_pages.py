def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any generated page is missing or stale",
    )
    ap.add_argument(
        "--clean", action="store_true", help="delete generated pages whose record has gone away"
    )
    args = ap.parse_args()
    mode = "check" if args.check else "write"

    data = read_data()
    validate(data)

    global HOST_CATEGORY_TITLES, ALL_HOSTS
    HOST_CATEGORY_TITLES = {k: v.get("title", k) for k, v in data["categories"].items()}
    ALL_HOSTS = data["hosts"]

    targets = {}  # abspath -> body
    wanted_dirs = set()

    targets[os.path.join(ROOT, "artists", "index.html")] = artist_index(data)

    for h in data["hosts"]:
        if h["category"] == "artists":
            p = os.path.join(ROOT, "artists", h["slug"], "index.html")
            targets[p] = host_page(h, data["hosts"])
            wanted_dirs.add(os.path.join(ROOT, h["slug"]))
            targets[os.path.join(ROOT, h["slug"], "index.html")] = alias_page(h, data["hosts"])
        else:
            p = os.path.join(ROOT, h["slug"], "index.html")
            targets[p] = host_page(h, data["hosts"])
            wanted_dirs.add(p)

    results = {}
    for path in sorted(targets):
        results[os.path.relpath(path, ROOT)] = write_if_changed(path, targets[path], mode)

    if args.clean:
        for d in sorted(wanted_dirs):
            if not os.path.isdir(d):
                continue
            for name in os.listdir(d):
                p = os.path.join(d, name)
                if not os.path.isfile(p):
                    continue
                with open(p, encoding="utf-8", newline="") as fh:
                    head = fh.read(400)
                if SIGNATURE not in head:
                    continue
                if os.path.abspath(p) in targets:
                    continue
                if mode == "check":
                    results[os.path.relpath(p, ROOT)] = "orphan"
                else:
                    os.remove(p)
                    results[os.path.relpath(p, ROOT)] = "removed"

    counts = {}
    for state in results.values():
        counts[state] = counts.get(state, 0) + 1

    for rel in sorted(results):
        if results[rel] != "unchanged":
            print("%-9s %s" % (results[rel], rel))

    print(
        "\n%d host records -> %d pages: %s"
        % (
            len(data["hosts"]),
            len(targets),
            ", ".join("%d %s" % (v, k) for k, v in sorted(counts.items())),
        )
    )

    bad = [r for r, s in results.items() if s in ("stale", "orphan")]
    if bad:
        sys.stderr.write(
            "\n%s\n"
            % (
                "out of date: " + ", ".join(bad)
                if args.check
                else "generation failed: " + ", ".join(bad)
            )
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
