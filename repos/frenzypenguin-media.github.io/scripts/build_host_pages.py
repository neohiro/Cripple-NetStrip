def read_data():
    with open(DATA, encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict) or "hosts" not in data or "categories" not in data:
        sys.exit("_data/hosts.yml has no `categories` / `hosts` keys")
    return data


def validate(data):
    """Fail loudly here rather than emitting 34 pages that are subtly wrong."""
    cats = data["categories"]
    seen = {}
    problems = []
    for i, h in enumerate(data["hosts"]):
        slug = h.get("slug")
        if not slug:
            problems.append("record %d has no slug" % i)
            continue
        if slug in seen:
            problems.append("duplicate slug %r (records %d and %d)" % (slug, seen[slug], i))
        seen[slug] = i
        if h.get("category") not in cats:
            problems.append("%s: category %r is not in categories:" % (slug, h.get("category")))
        if h.get("status") not in STATUS_RANK:
            problems.append(
                "%s: status %r is not one of %s" % (slug, h.get("status"), sorted(STATUS_RANK))
            )
        for key in ("title", "url", "type"):
            if not h.get(key):
                problems.append("%s: missing %s" % (slug, key))
    if problems:
        for p in problems:
            sys.stderr.write("hosts.yml: %s\n" % p)
        sys.exit(1)


def write_if_changed(path, body, mode="write"):
    """Returns 'unchanged' | 'written' | 'skipped' | 'stale'."""
    rel = os.path.relpath(path, ROOT)
    existing = None
    if os.path.exists(path):
        with open(path, encoding="utf-8", newline="") as fh:
            existing = fh.read()
        if existing == body:
            return "unchanged"
        if SIGNATURE not in existing:
            if mode == "check":
                return "skipped"
            sys.stderr.write("refusing to overwrite hand-edited %s\n" % rel)
            return "skipped"
    if mode == "check":
        return "stale"
    parent = os.path.dirname(path)
    if parent and not os.path.isdir(parent):
        os.makedirs(parent)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return "written"


def y_esc(text):
    """A YAML double-quoted scalar. Front matter only."""
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


_HTML_ESCAPES = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"}


def h_esc(text):
    """HTML text and double-quoted attribute values.

    Escapes the ampersand FIRST. Doing it later would double-escape the entities
    this function itself introduces, which is the classic way an escaper eats
    its own output on the second pass.
    """
    out = str(text)
    for char, entity in _HTML_ESCAPES.items():
        out = out.replace(char, entity)
    return out


def front_matter(fields):
    lines = ["---"]
    for key, value in fields:
        lines.append("%s: %s" % (key, value))
    lines.append("---")
    return "\n".join(lines)


def sibling_paths(host, all_hosts):
    """Other hosts kept by the same organisational account."""
    return [
        h for h in all_hosts if h["slug"] != host["slug"] and h.get("owner") == host.get("owner")
    ]


def same_category(host, all_hosts):
    return [h for h in all_hosts if h["slug"] != host["slug"] and h["category"] == host["category"]]


def path_for(host):
    if host["category"] == "artists":
        return "/artists/%s/" % host["slug"]
    return "/%s/" % host["slug"]


