def host_page(host, all_hosts):
    desc = host.get("blurb") or host.get("intro") or host["title"]
    path = path_for(host)
    fields = [
        ("layout", "host"),
        ("slug", y_esc(host["slug"])),
        ("title", y_esc("%s — %s" % (host["title"], host["slug"]))),
        ("description", y_esc(desc)),
        ("permalink", y_esc(path)),
    ]
    fm = front_matter(fields)
    css = "\n".join("  - %s" % c for c in EXTRA_CSS)
    js = "\n".join("  - %s" % j for j in EXTRA_JS)
    fm = fm.replace("---\n", "---\nextra_css:\n%s\nextra_js:\n%s\n" % (css, js), 1)

    if host["category"] == "artists":
        body = artist_body(host, all_hosts)
    else:
        body = standard_body(host, all_hosts)
    # Front matter must be byte 0 or Jekyll treats the whole file as static
    # HTML and never applies the layout. The signature therefore goes BELOW
    # the closing delimiter, where it still guards write_if_changed().
    return "%s\n%s\n\n%s\n%s\n" % (fm, SIGNATURE, body, SIGNATURE)


