def write_lang(code, core_entries, tt_entries=None):
    """Merge entries into an existing catalog (hand edits preserved)."""
    path = os.path.join(BASE, code + ".json")
    data = {}
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            data = {}
    for suf, text in core_entries.items():
        data[KEY[suf]] = text
    for raw, text in (tt_entries or {}).items():
        data["tooltip." + raw] = text
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
    return len(data)


